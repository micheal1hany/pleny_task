import Foundation

enum HTTPHeaders:String{
    case acceptLanguage = "Accept-Language"
    case contentType = "Content-Type"
    case applicationJson = "application/json"
    case accept = "Accept"
    case cacheControl = "Cache-Control"
    case auth = "Authorization"
    case noStore = "no-store"
}
